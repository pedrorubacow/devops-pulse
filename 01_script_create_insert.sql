DROP TABLE IF EXISTS incidente;
DROP TABLE IF EXISTS deploy;
DROP TABLE IF EXISTS execucao_pipeline;
DROP TABLE IF EXISTS projeto;
DROP TABLE IF EXISTS equipe;

-- ---------------------------------------------------------------------
-- 1. CRIAÇÃO DAS TABELAS
-- ---------------------------------------------------------------------

-- Equipes de desenvolvimento da empresa
CREATE TABLE equipe (
    id_equipe   SERIAL       PRIMARY KEY,
    nome        VARCHAR(60)  NOT NULL UNIQUE,
    area        VARCHAR(40)  NOT NULL,
    lider       VARCHAR(80)  NOT NULL
);

-- Projetos (repositórios) mantidos por cada equipe
CREATE TABLE projeto (
    id_projeto  SERIAL       PRIMARY KEY,
    nome        VARCHAR(60)  NOT NULL UNIQUE,
    linguagem   VARCHAR(30)  NOT NULL,
    id_equipe   INTEGER      NOT NULL REFERENCES equipe(id_equipe),
    criado_em   DATE         NOT NULL
);

-- Cada execução da pipeline de CI/CD de um projeto
CREATE TABLE execucao_pipeline (
    id_execucao  SERIAL       PRIMARY KEY,
    id_projeto   INTEGER      NOT NULL REFERENCES projeto(id_projeto),
    branch       VARCHAR(60)  NOT NULL,
    status       VARCHAR(10)  NOT NULL
                 CHECK (status IN ('SUCESSO', 'FALHA', 'CANCELADO')),
    iniciado_em  TIMESTAMP    NOT NULL,
    duracao_seg  INTEGER      NOT NULL CHECK (duracao_seg > 0),
    etapa_falha  VARCHAR(20)
                 CHECK (etapa_falha IN ('build', 'teste', 'scan_seguranca', 'deploy')),
    -- a etapa de falha só é preenchida quando a execução falhou
    CHECK ((status = 'FALHA') = (etapa_falha IS NOT NULL))
);

-- Deploys gerados por execuções com sucesso na branch main
CREATE TABLE deploy (
    id_deploy    SERIAL       PRIMARY KEY,
    id_execucao  INTEGER      NOT NULL REFERENCES execucao_pipeline(id_execucao),
    ambiente     VARCHAR(15)  NOT NULL
                 CHECK (ambiente IN ('homologacao', 'producao')),
    data_deploy  TIMESTAMP    NOT NULL,
    versao       VARCHAR(15)  NOT NULL,
    rollback     BOOLEAN      NOT NULL DEFAULT FALSE
);

-- Incidentes abertos em produção após um deploy
CREATE TABLE incidente (
    id_incidente  SERIAL       PRIMARY KEY,
    id_deploy     INTEGER      NOT NULL REFERENCES deploy(id_deploy),
    severidade    CHAR(4)      NOT NULL CHECK (severidade IN ('SEV1', 'SEV2', 'SEV3')),
    aberto_em     TIMESTAMP    NOT NULL,
    resolvido_em  TIMESTAMP,
    descricao     VARCHAR(120) NOT NULL,
    CHECK (resolvido_em IS NULL OR resolvido_em > aberto_em)
);

-- Índices nas chaves estrangeiras (acelerar os JOINs)
CREATE INDEX idx_projeto_equipe   ON projeto(id_equipe);
CREATE INDEX idx_execucao_projeto ON execucao_pipeline(id_projeto);
CREATE INDEX idx_deploy_execucao  ON deploy(id_execucao);
CREATE INDEX idx_incidente_deploy ON incidente(id_deploy);

